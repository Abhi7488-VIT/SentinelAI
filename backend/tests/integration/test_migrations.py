"""Migrations apply/revert cleanly, match the models, and enforce the schema constraints."""

from __future__ import annotations

import uuid

import pytest
from sqlalchemy import text
from sqlalchemy.exc import DBAPIError, IntegrityError
from sqlalchemy.ext.asyncio import AsyncEngine

from tests.integration.conftest import run_alembic

EXPECTED_TABLES = {
    "users",
    "organizations",
    "organization_members",
    "projects",
    "refresh_tokens",
    "audit_logs",
}


async def _tables(engine: AsyncEngine) -> set[str]:
    async with engine.connect() as conn:
        rows = await conn.execute(
            text("SELECT tablename FROM pg_tables WHERE schemaname = 'public'")
        )
        return {r[0] for r in rows}


async def test_downgrade_base_then_upgrade_head(engine: AsyncEngine) -> None:
    await run_alembic("downgrade", "base")
    assert await _tables(engine) == {"alembic_version"}

    await run_alembic("upgrade", "head")
    assert await _tables(engine) == EXPECTED_TABLES | {"alembic_version"}


async def test_models_match_migrations(engine: AsyncEngine) -> None:
    # Raises AutogenerateDiffsDetected if the ORM models drifted from the migrations.
    await run_alembic("check")


async def _exec(engine: AsyncEngine, sql: str, **params: object) -> None:
    async with engine.begin() as conn:
        await conn.execute(text(sql), params)


async def test_email_must_be_lowercase(engine: AsyncEngine) -> None:
    with pytest.raises(IntegrityError, match="ck_users_email_lowercase"):
        await _exec(
            engine,
            "INSERT INTO users (email, password_hash, display_name) VALUES ('A@x.io', 'h', 'A')",
        )


async def test_email_unique(engine: AsyncEngine) -> None:
    sql = "INSERT INTO users (email, password_hash, display_name) VALUES ('a@x.io', 'h', 'A')"
    await _exec(engine, sql)
    with pytest.raises(IntegrityError, match="uq_users_email"):
        await _exec(engine, sql)


@pytest.mark.parametrize("slug", ["Upper", "-lead", "trail-", "has space", "a_b", ""])
async def test_org_slug_format(engine: AsyncEngine, slug: str) -> None:
    with pytest.raises(IntegrityError, match="ck_organizations_slug_format"):
        await _exec(engine, "INSERT INTO organizations (name, slug) VALUES ('n', :s)", s=slug)


async def test_org_slug_length_limit(engine: AsyncEngine) -> None:
    with pytest.raises(DBAPIError, match=r"character varying\(63\)"):
        await _exec(engine, "INSERT INTO organizations (name, slug) VALUES ('n', :s)", s="x" * 64)


async def test_project_slug_unique_per_org_not_globally(engine: AsyncEngine) -> None:
    org_a, org_b = uuid.uuid4(), uuid.uuid4()
    await _exec(
        engine,
        "INSERT INTO organizations (id, name, slug) VALUES (:a, 'A', 'org-a'), (:b, 'B', 'org-b')",
        a=org_a,
        b=org_b,
    )
    insert = "INSERT INTO projects (org_id, name, slug) VALUES (:o, 'P', 'checkout')"
    await _exec(engine, insert, o=org_a)
    await _exec(engine, insert, o=org_b)  # same slug in another org is fine
    with pytest.raises(IntegrityError, match="uq_projects_org_id_slug"):
        await _exec(engine, insert, o=org_a)


async def test_member_role_check(engine: AsyncEngine) -> None:
    org, user = uuid.uuid4(), uuid.uuid4()
    await _exec(engine, "INSERT INTO organizations (id, name, slug) VALUES (:o, 'O', 'o')", o=org)
    await _exec(
        engine,
        "INSERT INTO users (id, email, password_hash, display_name) "
        "VALUES (:u, 'u@x.io', 'h', 'U')",
        u=user,
    )
    with pytest.raises(IntegrityError, match="ck_organization_members_role_valid"):
        await _exec(
            engine,
            "INSERT INTO organization_members (org_id, user_id, role) VALUES (:o, :u, 'root')",
            o=org,
            u=user,
        )
