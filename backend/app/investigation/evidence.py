"""`EvidenceService`: the only way evidence rows are created (plan §4, invariant 1).

Called only from `app/investigation/tools/` (an architecture test enforces it); there is no API
route that creates evidence and LLM output can only cite ids made here. Ids are generated by the
system. Re-recording the same tool call (same normalised parameters) in the same investigation
returns the existing row, so crash resume and retries never duplicate evidence (invariant 6).
"""

from __future__ import annotations

import base64
import hashlib
import json
import secrets
import uuid
from dataclasses import dataclass
from datetime import datetime
from typing import Any

from sqlalchemy.ext.asyncio import AsyncSession

from app.core.tenancy import TenantScope
from app.investigation.reduce import cap, fit_to_budget
from app.models.investigation import EVIDENCE_KINDS, EVIDENCE_SUMMARY_MAX_CHARS, Evidence
from app.repositories.investigations import EvidenceRepository

# Python-side budget for `data`; the database CHECK is 16 KiB, this leaves room for jsonb's own
# formatting differences.
DATA_BUDGET_BYTES = 15_000


def new_evidence_id() -> str:
    """`ev_` + 12 lowercase base32 characters (60 random bits)."""
    return "ev_" + base64.b32encode(secrets.token_bytes(8)).decode().lower()[:12]


def dedup_key(kind: str, params: dict[str, Any]) -> str:
    canonical = json.dumps(
        {"tool": kind, "params": params}, sort_keys=True, separators=(",", ":"), default=str
    )
    return hashlib.sha256(canonical.encode()).hexdigest()


@dataclass(frozen=True, slots=True)
class EvidenceDraft:
    kind: str
    params: dict[str, Any]
    service_ids: list[uuid.UUID]
    time_from: datetime
    time_to: datetime
    summary: str
    data: dict[str, Any]
    row_count: int
    truncated: bool


@dataclass(frozen=True, slots=True)
class Recorded:
    evidence: Evidence
    created: bool


class EvidenceService:
    def __init__(self, session: AsyncSession, scope: TenantScope) -> None:
        self._repo = EvidenceRepository(session, scope)

    async def record(
        self, investigation_id: uuid.UUID, node: str, draft: EvidenceDraft
    ) -> Recorded:
        if draft.kind not in EVIDENCE_KINDS:
            raise ValueError(f"unknown evidence kind {draft.kind!r}")
        if draft.time_from.tzinfo is None or draft.time_to.tzinfo is None:
            raise ValueError("evidence windows must be timezone-aware")
        if not draft.time_from < draft.time_to:
            raise ValueError("evidence window must be ordered and non-empty")
        data, trimmed = fit_to_budget(draft.data, DATA_BUDGET_BYTES)
        row, created = await self._repo.insert_once(
            {
                "id": new_evidence_id(),
                "investigation_id": investigation_id,
                "kind": draft.kind,
                "source_ref": {"tool": draft.kind, "params": draft.params},
                "service_ids": sorted({str(s) for s in draft.service_ids}),
                "time_from": draft.time_from,
                "time_to": draft.time_to,
                "summary": cap(draft.summary, EVIDENCE_SUMMARY_MAX_CHARS) or "",
                "data": data,
                "row_count": max(draft.row_count, 0),
                "truncated": draft.truncated or trimmed,
                "dedup_key": dedup_key(draft.kind, draft.params),
                "created_by_node": node[:32],
            }
        )
        return Recorded(row, created)
